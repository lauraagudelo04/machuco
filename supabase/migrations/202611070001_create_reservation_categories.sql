-- Reservation category master (booking module). The app reads it through the
-- REST API and caches it in the local Floor table `reservation_categories`.
create table if not exists public.reservation_categories (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(trim(name)) > 0)
);

alter table public.reservation_categories enable row level security;

grant select on table public.reservation_categories to anon, authenticated;

drop policy if exists "Public can read reservation categories"
  on public.reservation_categories;
create policy "Public can read reservation categories"
  on public.reservation_categories
  for select
  to anon, authenticated
  using (true);

insert into public.reservation_categories (id, name)
values
  (1, 'Sencilla'),
  (2, 'Doble'),
  (3, 'Suite'),
  (4, 'Jacuzzi'),
  (5, 'Temática')
on conflict (id) do update set name = excluded.name;

select setval(
  pg_get_serial_sequence('public.reservation_categories', 'id'),
  coalesce((select max(id) from public.reservation_categories), 1),
  true
);

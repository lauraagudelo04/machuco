-- PQRS configuration masters (read-only for the app):
--   allowed_image_formats : allowed image formats, with magic-byte signatures
--   pqrs_settings         : single-row general settings (id = 1)
--   pqrs_types            : catalog of PQRS types
--
-- Idempotent: it can be run on a database where the tables do not exist yet
-- (it creates them) or where they already exist with an older shape (it
-- renames/adds columns, constraints, triggers and policies). It never drops a
-- table or deletes rows. Edit the data from the Supabase dashboard or with the
-- service_role key; the app only has SELECT through RLS.
--
-- The limits below (900 KB per photo, at most 3 photos, the four type codes)
-- must match firestore.rules, which cannot read Supabase.

-- ---------------------------------------------------------------------------
-- 0. Shared trigger function: keeps updated_at current on every UPDATE.
-- ---------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- 1. Bring tables created earlier with other names/columns to the final shape.
--    Does nothing when those tables do not exist.
-- ---------------------------------------------------------------------------
do $$
begin
  if to_regclass('public.formatos_imagen_permitidos') is not null
     and to_regclass('public.allowed_image_formats') is null then
    alter table public.formatos_imagen_permitidos
      rename to allowed_image_formats;
  end if;

  if to_regclass('public.configuracion_pqrs') is not null
     and to_regclass('public.pqrs_settings') is null then
    alter table public.configuracion_pqrs rename to pqrs_settings;
  end if;

  if to_regclass('public.allowed_image_formats') is not null then
    if exists (select 1 from information_schema.columns
               where table_schema = 'public'
                 and table_name = 'allowed_image_formats'
                 and column_name = 'extensiones') then
      alter table public.allowed_image_formats
        rename column extensiones to extensions;
    end if;
    if exists (select 1 from information_schema.columns
               where table_schema = 'public'
                 and table_name = 'allowed_image_formats'
                 and column_name = 'firmas') then
      alter table public.allowed_image_formats
        rename column firmas to signatures;
    end if;
    if exists (select 1 from information_schema.columns
               where table_schema = 'public'
                 and table_name = 'allowed_image_formats'
                 and column_name = 'tamano_max_bytes') then
      alter table public.allowed_image_formats
        rename column tamano_max_bytes to max_size_bytes;
    end if;
    if exists (select 1 from information_schema.columns
               where table_schema = 'public'
                 and table_name = 'allowed_image_formats'
                 and column_name = 'activo') then
      alter table public.allowed_image_formats
        rename column activo to is_active;
    end if;
  end if;

  if to_regclass('public.pqrs_settings') is not null then
    if exists (select 1 from information_schema.columns
               where table_schema = 'public'
                 and table_name = 'pqrs_settings'
                 and column_name = 'max_fotos') then
      alter table public.pqrs_settings
        rename column max_fotos to max_photos;
    end if;
    if exists (select 1 from information_schema.columns
               where table_schema = 'public'
                 and table_name = 'pqrs_settings'
                 and column_name = 'calidad_imagen') then
      alter table public.pqrs_settings
        rename column calidad_imagen to image_quality;
    end if;
    if exists (select 1 from information_schema.columns
               where table_schema = 'public'
                 and table_name = 'pqrs_settings'
                 and column_name = 'ancho_max_px') then
      alter table public.pqrs_settings
        rename column ancho_max_px to max_width_px;
    end if;
    if exists (select 1 from information_schema.columns
               where table_schema = 'public'
                 and table_name = 'pqrs_settings'
                 and column_name = 'alto_max_px') then
      alter table public.pqrs_settings
        rename column alto_max_px to max_height_px;
    end if;
  end if;
end;
$$;

-- ---------------------------------------------------------------------------
-- 2. allowed_image_formats
-- ---------------------------------------------------------------------------
create table if not exists public.allowed_image_formats (
  id bigint generated by default as identity primary key,
  mime_type text not null,
  extensions text[] not null default '{}',
  -- Each signature: {"offset": <int>, "hex": "<bytes in hexadecimal>"}.
  -- A file must match ALL signatures of its format.
  signatures jsonb not null default '[]'::jsonb,
  max_size_bytes integer not null default 921600,
  is_active boolean not null default true,
  description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Columns that may be missing on a table created earlier.
alter table public.allowed_image_formats
  add column if not exists extensions text[] not null default '{}',
  add column if not exists signatures jsonb not null default '[]'::jsonb,
  add column if not exists max_size_bytes integer not null default 921600,
  add column if not exists is_active boolean not null default true,
  add column if not exists description text,
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists updated_at timestamptz not null default now();

-- 921600 bytes = 900 KB: the per-photo cap that fits a Firestore document.
update public.allowed_image_formats
set max_size_bytes = 921600
where max_size_bytes > 921600;

create unique index if not exists allowed_image_formats_mime_type_key
  on public.allowed_image_formats (mime_type);

-- "not valid": validates new/updated rows without failing on old rows.
alter table public.allowed_image_formats
  drop constraint if exists allowed_image_formats_mime_type_check,
  drop constraint if exists allowed_image_formats_extensions_check,
  drop constraint if exists allowed_image_formats_signatures_check,
  drop constraint if exists allowed_image_formats_max_size_bytes_check;
alter table public.allowed_image_formats
  add constraint allowed_image_formats_mime_type_check
    check (length(trim(mime_type)) > 0) not valid,
  add constraint allowed_image_formats_extensions_check
    check (cardinality(extensions) > 0) not valid,
  add constraint allowed_image_formats_signatures_check
    check (jsonb_typeof(signatures) = 'array') not valid,
  add constraint allowed_image_formats_max_size_bytes_check
    check (max_size_bytes between 1 and 921600) not valid;

drop trigger if exists set_allowed_image_formats_updated_at
  on public.allowed_image_formats;
create trigger set_allowed_image_formats_updated_at
  before update on public.allowed_image_formats
  for each row execute function public.set_updated_at();

insert into public.allowed_image_formats
  (mime_type, extensions, signatures, max_size_bytes, is_active, description)
values
  ('image/jpeg', array['jpg', 'jpeg'],
    '[{"offset":0,"hex":"FFD8FF"}]'::jsonb, 921600, true, 'JPEG'),
  ('image/png', array['png'],
    '[{"offset":0,"hex":"89504E470D0A1A0A"}]'::jsonb, 921600, true, 'PNG'),
  ('image/webp', array['webp'],
    '[{"offset":0,"hex":"52494646"},{"offset":8,"hex":"57454250"}]'::jsonb,
    921600, true, 'WebP (RIFF at offset 0 and WEBP at offset 8)')
on conflict (mime_type) do update set
  extensions = excluded.extensions,
  signatures = excluded.signatures,
  max_size_bytes = excluded.max_size_bytes,
  description = excluded.description;

-- ---------------------------------------------------------------------------
-- 3. pqrs_settings (single row, id = 1)
-- ---------------------------------------------------------------------------
create table if not exists public.pqrs_settings (
  id smallint primary key default 1,
  max_photos smallint not null default 3,
  image_quality smallint not null default 60,
  max_width_px integer not null default 1280,
  max_height_px integer not null default 1280,
  updated_at timestamptz not null default now()
);

alter table public.pqrs_settings
  add column if not exists max_photos smallint not null default 3,
  add column if not exists image_quality smallint not null default 60,
  add column if not exists max_width_px integer not null default 1280,
  add column if not exists max_height_px integer not null default 1280,
  add column if not exists updated_at timestamptz not null default now();

-- The app never sends more than 3 photos (Firestore rules enforce the same).
update public.pqrs_settings set max_photos = 3 where max_photos > 3;

alter table public.pqrs_settings
  drop constraint if exists pqrs_settings_id_check,
  drop constraint if exists pqrs_settings_max_photos_check,
  drop constraint if exists pqrs_settings_image_quality_check,
  drop constraint if exists pqrs_settings_max_width_px_check,
  drop constraint if exists pqrs_settings_max_height_px_check;
alter table public.pqrs_settings
  add constraint pqrs_settings_id_check check (id = 1) not valid,
  add constraint pqrs_settings_max_photos_check
    check (max_photos between 1 and 3) not valid,
  add constraint pqrs_settings_image_quality_check
    check (image_quality between 1 and 100) not valid,
  add constraint pqrs_settings_max_width_px_check
    check (max_width_px between 100 and 4096) not valid,
  add constraint pqrs_settings_max_height_px_check
    check (max_height_px between 100 and 4096) not valid;

drop trigger if exists set_pqrs_settings_updated_at on public.pqrs_settings;
create trigger set_pqrs_settings_updated_at
  before update on public.pqrs_settings
  for each row execute function public.set_updated_at();

insert into public.pqrs_settings (id) values (1) on conflict (id) do nothing;

-- ---------------------------------------------------------------------------
-- 4. pqrs_types (catalog of PQRS types)
-- ---------------------------------------------------------------------------
create table if not exists public.pqrs_types (
  id bigint generated by default as identity primary key,
  code text not null,
  name text not null,
  description text not null default '',
  response_days smallint not null default 15,
  allows_photos boolean not null default true,
  sort_order smallint not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.pqrs_types
  add column if not exists description text not null default '',
  add column if not exists response_days smallint not null default 15,
  add column if not exists allows_photos boolean not null default true,
  add column if not exists sort_order smallint not null default 0,
  add column if not exists is_active boolean not null default true,
  add column if not exists created_at timestamptz not null default now(),
  add column if not exists updated_at timestamptz not null default now();

create unique index if not exists pqrs_types_code_key
  on public.pqrs_types (code);

-- The code list must match the type check in firestore.rules.
alter table public.pqrs_types
  drop constraint if exists pqrs_types_code_check,
  drop constraint if exists pqrs_types_name_check,
  drop constraint if exists pqrs_types_response_days_check;
alter table public.pqrs_types
  add constraint pqrs_types_code_check
    check (code in ('peticion', 'queja', 'reclamo', 'sugerencia')) not valid,
  add constraint pqrs_types_name_check
    check (length(trim(name)) > 0) not valid,
  add constraint pqrs_types_response_days_check
    check (response_days between 1 and 90) not valid;

drop trigger if exists set_pqrs_types_updated_at on public.pqrs_types;
create trigger set_pqrs_types_updated_at
  before update on public.pqrs_types
  for each row execute function public.set_updated_at();


create table if not exists public.room_included_services (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(trim(name)) > 0)
);

alter table public.room_included_services enable row level security;

grant select on table public.room_included_services to anon, authenticated;

drop policy if exists "Public can read room included services"
  on public.room_included_services;
create policy "Public can read room included services"
  on public.room_included_services
  for select
  to anon, authenticated
  using (true);

insert into public.room_included_services (id, name)
values
  (1, 'Jacuzzi'),
  (2, 'Luces'),
  (3, 'Mini bar'),
  (4, 'Fogata')
on conflict (id) do update set name = excluded.name;

select setval(
  pg_get_serial_sequence('public.room_included_services', 'id'),
  coalesce((select max(id) from public.room_included_services), 1),
  true
);

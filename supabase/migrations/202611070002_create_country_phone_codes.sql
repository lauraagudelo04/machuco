-- Country phone code master of the auth module. Columns match what
-- AuthCatalogRepository reads (lib/database/repository/auth) and caches in
-- the local SQLite table `country_phone_codes`. Countries mirror the
-- `phone_country_codes` master; unifying both masters is still pending.
create table if not exists public.country_phone_codes (
  id bigint generated by default as identity primary key,
  iso_code text not null unique check (iso_code ~ '^[A-Z]{2}$'),
  country_name text not null check (length(trim(country_name)) > 0),
  dial_code text not null check (dial_code ~ '^\+[0-9]{1,4}$'),
  flag_emoji text,
  phone_min_length integer not null check (phone_min_length > 0),
  phone_max_length integer not null,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  check (phone_max_length >= phone_min_length)
);

alter table public.country_phone_codes enable row level security;

grant select on table public.country_phone_codes to anon, authenticated;

drop policy if exists "Public can read country phone codes"
  on public.country_phone_codes;
create policy "Public can read country phone codes"
  on public.country_phone_codes
  for select
  to anon, authenticated
  using (true);


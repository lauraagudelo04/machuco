import 'dart:async';

import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:flutter/foundation.dart';
import 'package:machuco/database/model/pqrs/pqrs_firestore_document.dart';
import 'package:machuco/database/repository/pqrs/pqrs_repository.dart';
import 'package:machuco/models/pqrs/pqrs.dart';
import 'package:machuco/service/firebase/firestore_collections.dart';

/// Maximum photos per trace entry; mirrors the `_1` to `_3` id suffixes that
/// `firestore.rules` accepts.
const pqrsMaxPhotosPerEntry = 3;

const _connectionMessage =
    'No hay conexión con el servidor. Revisa tu internet e intenta de nuevo';
const _permissionMessage = 'No tienes permiso para realizar esta acción';
const _preconditionMessage =
    'La solicitud cambió o no admite esta acción. Actualiza e intenta de nuevo';
const _notFoundMessage = 'La solicitud ya no existe';
const _invalidDataMessage = 'El servidor devolvió datos que no se pueden leer';
const _unknownMessage = 'Ocurrió un error inesperado. Intenta de nuevo';

/// Classifies an error raised by Firestore into a [PqrsFailure].
///
/// Network and timeout errors are retryable ([PqrsFailureKind.connection]);
/// `permission-denied` and `failed-precondition` are not and are told apart.
/// The message never carries document data.
PqrsFailure pqrsFailureFromError(Object error) {
  if (error is PqrsFailure) return error;
  if (error is TimeoutException) {
    return const PqrsFailure(PqrsFailureKind.connection, _connectionMessage);
  }
  if (error is FormatException) {
    return const PqrsFailure(PqrsFailureKind.unknown, _invalidDataMessage);
  }
  if (error is FirebaseException) {
    // Only the code is logged: the message may mention document paths.
    debugPrint('PQRS Firestore error: ${error.code}');
    return switch (error.code) {
      'unavailable' || 'deadline-exceeded' || 'network-request-failed' =>
        const PqrsFailure(PqrsFailureKind.connection, _connectionMessage),
      'permission-denied' || 'unauthenticated' => const PqrsFailure(
        PqrsFailureKind.permission,
        _permissionMessage,
      ),
      // Also raised when a composite index is missing or a state precondition
      // fails; not retryable as it is.
      'failed-precondition' || 'already-exists' || 'aborted' =>
        const PqrsFailure(PqrsFailureKind.validation, _preconditionMessage),
      'not-found' => const PqrsFailure(
        PqrsFailureKind.notFound,
        _notFoundMessage,
      ),
      _ => const PqrsFailure(PqrsFailureKind.unknown, _unknownMessage),
    };
  }
  debugPrint('PQRS: unexpected ${error.runtimeType}');
  return const PqrsFailure(PqrsFailureKind.unknown, _unknownMessage);
}

/// [PqrsRepository] backed by Cloud Firestore.
///
/// Every action is ONE `WriteBatch` (request when it changes, trace entry and
/// photos), with ids generated by the client so a retry is idempotent. The
/// instants `createdAt`, `updatedAt` and `resolvedAt` are server timestamps.
/// The rules in `firestore.rules` are the real authority; the checks of the
/// controller only simulate them.
///
/// There is no local queue here: [retryPending] and [discardPending] do
/// nothing until the synchronized repository of Stage 5 wraps this one. With
/// no connection Firestore keeps the batch in its own cache and the commit
/// future never completes, so it ends as a [PqrsFailureKind.connection]
/// timeout while the write may still be delivered later (same ids).
class FirestorePqrsRepository implements PqrsRepository {
  FirestorePqrsRepository({
    FirebaseFirestore? firestore,
    this.requestTimeout = const Duration(seconds: 10),
  }) : _firestore = firestore ?? FirebaseFirestore.instance;

  final FirebaseFirestore _firestore;
  final Duration requestTimeout;

  static const _estimate = GetOptions(
    serverTimestampBehavior: ServerTimestampBehavior.estimate,
  );

  CollectionReference<Map<String, dynamic>> get _requests =>
      _firestore.collection(FirestoreCollections.pqrs);

  // ---------------------------------------------------------------- writes

  @override
  Future<PqrsRecord> create(PqrsNewRequest newRequest) async {
    try {
      final photos = PqrsFirestoreDocument.storablePhotos(newRequest.photos);
      _checkPhotoCount(photos);
      // The owner is copied from the motel mirror so the rules can compare it.
      final ownerId = await _ownerOfMotel(newRequest.motelId);

      final requestRef = _requests.doc(newRequest.id);
      final traceId = pqrsOpeningTraceId(newRequest.id);
      final opening = PqrsTraceEntry(
        id: traceId,
        author: PqrsActor.client,
        authorId: newRequest.clientId,
        authorName: newRequest.clientName,
        message: newRequest.description,
        createdAt: newRequest.createdAt,
        attachments: photos,
      );

      final batch = _firestore.batch()
        ..set(
          requestRef,
          PqrsFirestoreDocument.newRequestToFirestore(
            newRequest,
            ownerId: ownerId,
          ),
        );
      _addTrace(batch, requestRef, opening);
      await batch.commit().timeout(requestTimeout);

      return PqrsRecord(
        request: PqrsRequest(
          id: newRequest.id,
          motelId: newRequest.motelId,
          motelName: newRequest.motelName,
          clientId: newRequest.clientId,
          clientName: newRequest.clientName,
          ownerId: ownerId,
          type: newRequest.type,
          subject: newRequest.subject,
          description: newRequest.description,
          createdAt: newRequest.createdAt,
          attachments: photos,
        ),
      );
    } on Object catch (error) {
      throw pqrsFailureFromError(error);
    }
  }

  @override
  Future<PqrsRecord> appendTrace(PqrsTraceAppend action) async {
    try {
      final photos = PqrsFirestoreDocument.storablePhotos(
        action.entry.attachments,
      );
      _checkPhotoCount(photos);

      final requestRef = _requests.doc(action.requestId);
      final batch = _firestore.batch();
      _addTrace(batch, requestRef, action.entry);
      final update = PqrsFirestoreDocument.updateToFirestore(action);
      if (update != null) batch.update(requestRef, update);
      await batch.commit().timeout(requestTimeout);
    } on Object catch (error) {
      throw pqrsFailureFromError(error);
    }
    final record = await getDetail(action.requestId);
    if (record == null) {
      throw const PqrsFailure(PqrsFailureKind.notFound, _notFoundMessage);
    }
    return record;
  }

  /// Adds the trace entry and its photos (ids `<traceId>_1` to `_3`).
  void _addTrace(
    WriteBatch batch,
    DocumentReference<Map<String, dynamic>> requestRef,
    PqrsTraceEntry entry,
  ) {
    batch.set(
      requestRef.collection(FirestoreCollections.traces).doc(entry.id),
      PqrsFirestoreDocument.traceToFirestore(entry),
    );
    final photos = PqrsFirestoreDocument.storablePhotos(entry.attachments);
    for (var index = 0; index < photos.length; index++) {
      batch.set(
        requestRef
            .collection(FirestoreCollections.photos)
            .doc(pqrsPhotoId(entry.id, index + 1)),
        PqrsFirestoreDocument.photoToFirestore(
          photos[index],
          traceId: entry.id,
          authorId: entry.authorId,
          authorRole: entry.author,
        ),
      );
    }
  }

  void _checkPhotoCount(List<PqrsAttachment> photos) {
    if (photos.length > pqrsMaxPhotosPerEntry) {
      throw const PqrsFailure(
        PqrsFailureKind.validation,
        'Solo puedes adjuntar hasta $pqrsMaxPhotosPerEntry fotos',
      );
    }
  }

  /// Reads `motels/{motelId}.ownerId`. The existing motel registry only
  /// writes the mirror, so it is read here with the injected Firestore.
  Future<String> _ownerOfMotel(String motelId) async {
    final snapshot = await _firestore
        .collection(FirestoreCollections.motels)
        .doc(motelId)
        .get()
        .timeout(requestTimeout);
    final data = snapshot.data();
    if (!snapshot.exists || data == null) {
      throw const PqrsFailure(
        PqrsFailureKind.notFound,
        'El motel ya no está disponible',
      );
    }
    final ownerId = data['ownerId'];
    if (ownerId is! String || ownerId.isEmpty) {
      throw const PqrsFailure(
        PqrsFailureKind.validation,
        'No se pudo identificar al propietario del motel',
      );
    }
    return ownerId;
  }

  // ----------------------------------------------------------------- reads

  @override
  Future<List<PqrsRecord>> listByClient(String clientId) => _list(
    _requests
        .where('clientId', isEqualTo: clientId)
        .orderBy('createdAt', descending: true),
  );

  @override
  Future<List<PqrsRecord>> listByOwner(String ownerId) => _list(
    _requests
        .where('ownerId', isEqualTo: ownerId)
        .orderBy('createdAt', descending: true),
  );

  @override
  Future<List<PqrsRecord>> listAll() =>
      _list(_requests.orderBy('createdAt', descending: true));

  /// Lists carry no trace or photos: those are loaded in the detail.
  Future<List<PqrsRecord>> _list(Query<Map<String, dynamic>> query) async {
    try {
      final snapshot = await query.get(_estimate).timeout(requestTimeout);
      return List.unmodifiable(
        snapshot.docs.map(
          (doc) => PqrsRecord(
            request: PqrsFirestoreDocument.requestFromFirestore(
              doc.id,
              doc.data(),
            ),
          ),
        ),
      );
    } on Object catch (error) {
      throw pqrsFailureFromError(error);
    }
  }

  @override
  Future<PqrsRecord?> getDetail(String requestId) async {
    try {
      final requestRef = _requests.doc(requestId);
      final snapshot = await requestRef.get(_estimate).timeout(requestTimeout);
      final data = snapshot.data();
      if (!snapshot.exists || data == null) return null;

      final traces = await requestRef
          .collection(FirestoreCollections.traces)
          .orderBy('createdAt')
          .get(_estimate)
          .timeout(requestTimeout);
      final openingId = pqrsOpeningTraceId(requestId);
      final entries = [
        for (final doc in traces.docs)
          // The opening entry only carries the photos of the request.
          if (doc.id != openingId)
            PqrsFirestoreDocument.traceFromFirestore(doc.id, doc.data()),
      ];
      return PqrsRecord(
        request: PqrsFirestoreDocument.requestFromFirestore(
          snapshot.id,
          data,
          trace: List.unmodifiable(entries),
        ),
      );
    } on Object catch (error) {
      throw pqrsFailureFromError(error);
    }
  }

  @override
  Future<List<PqrsAttachment>> getPhotos(String requestId) async {
    try {
      final snapshot = await _requests
          .doc(requestId)
          .collection(FirestoreCollections.photos)
          .orderBy('createdAt')
          .get(_estimate)
          .timeout(requestTimeout);
      return List.unmodifiable([
        for (var index = 0; index < snapshot.docs.length; index++)
          PqrsFirestoreDocument.photoFromFirestore(
            snapshot.docs[index].id,
            snapshot.docs[index].data(),
            index + 1,
          ),
      ]);
    } on Object catch (error) {
      throw pqrsFailureFromError(error);
    }
  }

  // ------------------------------------------------------- local queue (n/a)

  @override
  Future<void> retryPending({String? requestId}) async {}

  @override
  Future<void> discardPending(String requestId) async {}
}
